import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { probeTicketingApi, inferFieldMap } from '../ticketing/probe.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const envPath = path.resolve(__dirname, '../../../.env');

function patchEnv(updates) {
  if (!fs.existsSync(envPath)) {
    console.warn(`[probe] .env not found at ${envPath}; skipping write.`);
    return;
  }
  let text = fs.readFileSync(envPath, 'utf8');
  for (const [k, v] of Object.entries(updates)) {
    const line = `${k}=${v}`;
    const re = new RegExp(`^${k}=.*$`, 'm');
    text = re.test(text) ? text.replace(re, line) : text.trimEnd() + `\n${line}\n`;
  }
  fs.writeFileSync(envPath, text);
  console.log(`[probe] updated .env with: ${Object.keys(updates).join(', ')}`);
}

const result = await probeTicketingApi();
if (!result.success) {
  console.error('\n[probe] could not auto-detect ticket list endpoint. Attempts:');
  for (const a of result.attempts) {
    console.error(` - style=${a.style} path=${a.path} ok=${a.ok} reason=${a.reason || 'n/a'}`);
  }
  console.error('\nTry setting TICKETING_AUTH_STYLE and TICKETING_LIST_ENDPOINT manually in .env, then re-run.');
  process.exit(1);
}

console.log(`\n[probe] SUCCESS`);
console.log(`  auth style: ${result.style}`);
console.log(`  list path:  ${result.listEndpoint}`);
console.log(`  sample ticket keys: ${result.sample ? Object.keys(result.sample).join(', ') : '(none)'}`);

const fieldMap = inferFieldMap(result.sample);
console.log('\n[probe] inferred field map (edit backend/src/ticketing/mapping.js if wrong):');
console.log(JSON.stringify(fieldMap, null, 2));

patchEnv({
  TICKETING_AUTH_STYLE: result.style,
  TICKETING_LIST_ENDPOINT: result.listEndpoint,
});

const mappingPath = path.resolve(__dirname, '../ticketing/mapping.js');
const mappingContent = `// Auto-generated by \`npm run probe\`. Edit if a field is wrong.\nexport const fieldMap = ${JSON.stringify(fieldMap, null, 2)};\n`;
fs.writeFileSync(mappingPath, mappingContent);
console.log(`[probe] wrote field map to ${mappingPath}`);

console.log('\nNext: `npm run sync:now` to pull & index tickets, then `npm run dev`.');
